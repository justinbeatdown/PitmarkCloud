class Markup(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tags=[]
        self.attrs=[]
    def handle_starttag(self,tag,attrs):
        self.tags.append(tag)
        self.attrs.append((tag,dict(attrs)))

for template in (site,profile):
    doc=Markup()
    doc.feed(template)
