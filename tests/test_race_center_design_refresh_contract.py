# Simple CSS lexical balance check (comments/quotes ignored).
def check_css(text):
    text=re.sub(r"/\*.*?\*/","",text,flags=re.S)
    stack=[]
    quote=None
    escape=False
    for ch in text:
        if quote:
            if escape:escape=False
            elif ch=="\\":escape=True
            elif ch==quote:quote=None
            continue
        if ch in ("'",'"'):
            quote=ch
            continue
        if ch in "({[":stack.append(ch)
        elif ch in ")}]":
            assert stack and "({[".index(stack.pop())==")}]" .index(ch),ch
    assert not quote and not stack,(quote,stack)
check_css(css)
